// التحديثُ الجوّيّ — الوصولُ الفوريّ
// ═══════════════════════════════════════════════════════════════
// expo-updates وحدَه يسألُ **عندَ الإقلاعِ الباردِ فقط**، ويُطبّقُ ما نزلَ في
// الإقلاعِ الذي يليه. وأكثرُ الأطبّاءِ لا يُنهونَ التطبيقَ أبدًا — يتركونَه في
// الخلفيّةِ أيّامًا — فيبقونَ على شيفرةٍ قديمةٍ ونحنُ نظنُّ أنّنا حدّثناهم.
//
// فهذه الطبقةُ تنقلُ القرارَ إلينا: **نفحصُ ونُنزّلُ ونُطبّقُ متى شئنا**.
//   • عندَ عودةِ التطبيقِ من الخلفيّةِ إلى الواجهة
//   • ودوريًّا وهو مفتوحٌ يعمل
//   • ثمّ يُعادُ تحميلُه في الحال
//
// والقرارُ اتُّخِذَ عن علم: إعادةُ التحميلِ الفوريّةُ قد تقعُ والطبيبُ يعمل،
// فيضيعُ **ما لم يُحفَظْ بعد** — نموذجٌ نصفُ مملوءٍ أو رسالةٌ لم تُرسَل. وكلُّ
// ما بلغَ قاعدةَ البياناتِ في أمانٍ لا يمسُّه شيء. وقد رُجِّحَ أنّ لحظةَ انقطاعٍ
// نادرةً أهونُ من أسبوعٍ يعملُ فيه المركزُ بمنطقٍ قديم.
import { useEffect, useRef } from 'react';
import { AppState, AppStateStatus } from 'react-native';
import * as Updates from 'expo-updates';

// كلَّ عشرِ دقائقَ وهو مفتوح. السؤالُ نداءٌ صغيرٌ جدًّا (بضعُ مئاتٍ من البايتات)
// لا يُثقِلُ شبكةَ مركزٍ ولا بطّاريّة، ويجعلُ أبعدَ تأخيرٍ عشرَ دقائقَ لا يومًا.
const EVERY_MS = 10 * 60 * 1000;

/** يفحصُ التحديثَ الجوّيَّ ويُطبّقُه فورَ نزولِه. يُركَّبُ مرّةً واحدةً في جذرِ التطبيق. */
export function useInstantUpdates(): void {
  // حارسٌ ضدَّ التزامُن: العودةُ من الخلفيّةِ قد تقعُ مع نبضةِ المؤقّتِ في اللحظةِ
  // نفسِها، فيجري فحصانِ معًا ويُنزَّلُ الملفُّ مرّتَين.
  const busy = useRef(false);

  useEffect(() => {
    // في التطويرِ لا وجودَ لتحديثاتٍ جوّيّةٍ أصلًا، وreloadAsync يرمي خطأً.
    if (__DEV__ || !Updates.isEnabled) return;

    let alive = true;

    const sweep = async () => {
      if (busy.current || !alive) return;
      busy.current = true;
      try {
        const found = await Updates.checkForUpdateAsync();
        if (!found.isAvailable || !alive) return;
        await Updates.fetchUpdateAsync();
        if (!alive) return;
        // لا يعودُ من هذا النداء: تُستأنَفُ الطبقةُ البرمجيّةُ من جديدٍ بالشيفرةِ الجديدة.
        await Updates.reloadAsync();
      } catch {
        // شبكةٌ منقطعةٌ أو خادمٌ لا يردّ — نصمتُ ونُعاودُ في النبضةِ التالية.
        // لا يصحُّ أن يُقلِقَ الطبيبَ عُطلٌ لا شأنَ له به.
      } finally {
        busy.current = false;
      }
    };

    const onState = (s: AppStateStatus) => { if (s === 'active') sweep(); };
    const sub = AppState.addEventListener('change', onState);
    const timer = setInterval(sweep, EVERY_MS);
    sweep();

    return () => { alive = false; sub.remove(); clearInterval(timer); };
  }, []);
}

/* بوّابةُ النسخة — القاعدةُ الصافية.
 * لا شبكةَ ولا قاعدةَ بيانات: cmpVersion و gateFor وحدَهما.
 *   npx tsx scripts/test-version-gate.ts
 */
import { cmpVersion, gateFor } from '../lib/versionRules';

let pass = 0, fail = 0;
const ok = (name: string, got: unknown, want: unknown) => {
  const good = JSON.stringify(got) === JSON.stringify(want);
  if (good) { pass++; } else { fail++; console.log(`  ❌ ${name}\n       جاء: ${JSON.stringify(got)}\n     المنتظَر: ${JSON.stringify(want)}`); }
};
const head = (t: string) => console.log(`\n── ${t} ──`);

// ═══ ① المقارنةُ رقمًا لا نصًّا ═══
head('المقارنة');
ok('متساويتان', cmpVersion('1.0.13', '1.0.13'), 0);
ok('أقدم', cmpVersion('1.0.12', '1.0.13'), -1);
ok('أحدث', cmpVersion('1.0.14', '1.0.13'), 1);
// الفخُّ الأصليّ: نصًّا «1.0.9» > «1.0.10» لأنّ '9' > '1'. ورقمًا العكس.
ok('9 أقدم من 10 (لا نصًّا)', cmpVersion('1.0.9', '1.0.10'), -1);
ok('10 أحدث من 9', cmpVersion('1.0.10', '1.0.9'), 1);
ok('99 أقدم من 100', cmpVersion('1.0.99', '1.0.100'), -1);
ok('اختلافُ الوسط', cmpVersion('1.1.0', '1.0.99'), 1);
ok('اختلافُ الكبير', cmpVersion('2.0.0', '1.99.99'), 1);
// الأقصرُ يُكمَّلُ بأصفار
ok('1.1 = 1.1.0', cmpVersion('1.1', '1.1.0'), 0);
ok('1.1 أقدم من 1.1.1', cmpVersion('1.1', '1.1.1'), -1);
ok('1 = 1.0.0', cmpVersion('1', '1.0.0'), 0);
// مدخلاتٌ رديئةٌ لا تُسقِطُ التطبيق
ok('فراغ = صفر', cmpVersion('', '0.0.0'), 0);
ok('نصٌّ غريب', cmpVersion('abc', '0'), 0);
ok('مسافاتٌ تُقصّ', cmpVersion(' 1.0.13 ', '1.0.13'), 0);

// ═══ ② أيُّ حاجزٍ يستحقُّه الجهاز ═══
head('القرار');
ok('لا رقمَ مضبوطٌ → مفتوح', gateFor('1.0.13', null, null), 'ok');
ok('أحدثُ من المطلوب', gateFor('1.0.14', '1.0.13', '1.0.13'), 'ok');
ok('مطابقٌ للمطلوب', gateFor('1.0.13', '1.0.13', null), 'ok');
ok('أقدمُ من المطلوب → منع', gateFor('1.0.12', '1.0.13', null), 'block');
ok('أقدمُ من المقترَح → شريط', gateFor('1.0.12', null, '1.0.13'), 'suggest');
ok('مطابقٌ للمقترَح → مفتوح', gateFor('1.0.13', null, '1.0.13'), 'ok');
// الإلزامُ يغلبُ الاقتراحَ دائمًا
ok('أقدمُ منهما → منع لا شريط', gateFor('1.0.11', '1.0.13', '1.0.14'), 'block');
ok('بينهما → شريط', gateFor('1.0.13', '1.0.13', '1.0.14'), 'suggest');
// أمانُ الفشل: لا نحجبُ أحدًا إن جهلنا نسختَه
ok('نسختُنا مجهولة → مفتوح', gateFor('', '9.9.9', '9.9.9'), 'ok');
// الترقيمُ ذو الخانتَين لا يخدعُها
ok('1.0.9 أمام مطلوب 1.0.10 → منع', gateFor('1.0.9', '1.0.10', null), 'block');
ok('1.0.10 أمام مطلوب 1.0.9 → مفتوح', gateFor('1.0.10', '1.0.9', null), 'ok');

// ═══ ③ سيناريو حقيقيّ: ما يجري عندَ إصدارِ 1.0.14 ═══
head('سيناريو الإصدار');
const R = '1.0.14';
ok('طبيبٌ على 1.0.11 (متجمّدٌ جوّيًّا)', gateFor('1.0.11', R, null), 'block');
ok('طبيبٌ على 1.0.13', gateFor('1.0.13', R, null), 'block');
ok('طبيبٌ حدَّثَ', gateFor('1.0.14', R, null), 'ok');
// وقبلَ رفعِ الرقم: الإصدارُ وحدَه لا يُجبِرُ أحدًا
ok('نُشِرَت 1.0.14 والرقمُ لم يُرفَعْ بعد', gateFor('1.0.13', null, null), 'ok');

console.log(`\n${fail === 0 ? '✅' : '❌'}  ${pass} ناجح · ${fail} فاشل\n`);
process.exit(fail === 0 ? 0 : 1);
